async function seed() {
  console.log('🌱 Starting FERMS Database Seeding (Idempotent)...');

  // 1. Seed Users (with bcrypt hashes) via idempotent upsert
  console.log('  -> Seeding Users with bcrypt hashed passwords...');
  for (const u of USERS_DATA) {
    const passwordHash = await bcrypt.hash(u.passwordRaw, 10);
    await prisma.user.upsert({
      where: { id: u.id },
      update: {
        name: u.name,
        email: u.email,
        passwordHash,
        phone: u.phone,
        role: u.role,
        status: u.status,
        station: u.station,
        assignedUnit: u.assignedUnit || null,
      },
      create: {
        id: u.id,
        name: u.name,
        email: u.email,
        passwordHash,
        phone: u.phone,
        role: u.role,
        status: u.status,
        station: u.station,
        assignedUnit: u.assignedUnit || null,
      },
    });
  }

  // 2. Seed FireStations via idempotent upsert
  console.log('  -> Seeding Fire Stations...');
  for (const s of STATIONS_DATA) {
    await prisma.fireStation.upsert({
      where: { id: s.id },
      update: s,
      create: s,
    });
  }

  // 3. Seed Incidents and Activity Logs via idempotent upsert
  console.log('  -> Seeding Incidents and Activity Logs...');
  for (const inc of INCIDENTS_DATA) {
    const { activityLog, ...incidentData } = inc;
    await prisma.incident.upsert({
      where: { id: inc.id },
      update: incidentData,
      create: incidentData,
    });

    // Ensure activity log entries exist without duplication
    for (const act of activityLog) {
      const existing = await prisma.incidentActivity.findFirst({
        where: {
          incidentId: inc.id,
          action: act.action,
          type: act.type,
        },
      });
      if (!existing) {
        await prisma.incidentActivity.create({
          data: {
            incidentId: inc.id,
            time: act.time,
            action: act.action,
            type: act.type,
          },
        });
      }
    }
  }

  // 4. Seed FireUnits via idempotent upsert
  console.log('  -> Seeding Fire Units...');
  for (const u of UNITS_DATA) {
    await prisma.fireUnit.upsert({
      where: { id: u.id },
      update: u,
      create: u,
    });
  }

  // 5. Seed Dispatches for active assignments (none active when all units are Available)
  console.log('  -> Seeding Active Dispatches...');
  const activeDispatches = [];

  for (const d of activeDispatches) {
    await prisma.dispatch.create({
      data: {
        incidentId: d.incidentId,
        unitId: d.unitId,
        dispatchedBy: 'USR-002', // Priya Sharma (Dispatcher)
        estimatedArrival: d.eta,
        dispatchedAt: d.dispatchedAt,
        arrivedAt: d.arrivedAt || null,
        status: 'Active',
      },
    });
  }

  // 6. Seed Notifications via idempotent upsert
  console.log('  -> Seeding Notifications...');
  for (const n of NOTIFICATIONS_DATA) {
    await prisma.notification.upsert({
      where: { id: n.id },
      update: n,
      create: n,
    });
  }

  console.log('✅ Database seeded successfully with all FERMS production records!\n');
}

seed()
  .catch((e) => {
    console.error('❌ Seeding Error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
